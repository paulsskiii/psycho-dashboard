// tokens.json → dist/tokens.css (custom properties) + dist/index.ts (typed constants).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));
const { min, max } = t.viewport;

// Fluid size between the two viewports: clamp(a, b + m·vw, c).
function fluid([lo, hi]) {
  if (lo === hi) return `${lo}px`;
  const slope = (hi - lo) / (max - min);
  const intercept = lo - slope * min;
  const vw = +(slope * 100).toFixed(4);
  return `clamp(${lo}px, ${+intercept.toFixed(3)}px + ${vw}vw, ${hi}px)`;
}

const lines = [":root {"];
for (const [k, v] of Object.entries(t.color)) lines.push(`  --${k}: ${v};`);
for (const [k, v] of Object.entries(t.data.sport)) lines.push(`  --sport-${k}: ${v};`);
for (const [k, v] of Object.entries(t.data.sleep)) lines.push(`  --sleep-${k}: ${v};`);
t.data.zones.forEach((v, i) => lines.push(`  --zone-${i + 1}: ${v};`));
t.data.diverging.fatigued.forEach((v, i) => lines.push(`  --div-fatigued-${i + 1}: ${v};`));
lines.push(`  --div-mid: ${t.data.diverging.mid};`);
t.data.diverging.fresh.forEach((v, i) => lines.push(`  --div-fresh-${i + 1}: ${v};`));
for (const [k, v] of Object.entries(t.data.status)) lines.push(`  --status-${k}: ${v};`);
t.space.forEach((v, i) => lines.push(`  --space-${i + 1}: ${v}px;`));
for (const [k, v] of Object.entries(t.radius)) lines.push(`  --radius-${k}: ${v}px;`);
for (const [k, v] of Object.entries(t.type)) {
  if (k.startsWith("$")) continue;
  lines.push(`  --fs-${k}: ${fluid(v)};`);
}
lines.push("}", "");

const ts = `// Generated by packages/tokens/build.mjs from tokens.json. Do not edit.
export const color = ${JSON.stringify(t.color, null, 2)} as const;
export const sport = ${JSON.stringify(t.data.sport, null, 2)} as const;
export const sleep = ${JSON.stringify(t.data.sleep, null, 2)} as const;
export const zones = ${JSON.stringify(t.data.zones)} as const;
export const diverging = ${JSON.stringify(t.data.diverging, null, 2)} as const;
export const status = ${JSON.stringify(t.data.status, null, 2)} as const;
export const space = ${JSON.stringify(t.space)} as const;
export const radius = ${JSON.stringify(t.radius)} as const;
export type Sport = keyof typeof sport;
export type SleepStage = keyof typeof sleep;
export type Status = keyof typeof status;
`;

mkdirSync(join(here, "dist"), { recursive: true });
writeFileSync(join(here, "dist", "tokens.css"), lines.join("\n"));
writeFileSync(join(here, "dist", "index.ts"), ts);
console.log(`tokens: ${lines.length - 3} css vars → dist/tokens.css, dist/index.ts`);
